<h4>Back Cover Description</h4>
<p>
    <strong>Cameron Thorpe</strong> has spent the last decade buried in code, research, and lecture halls &mdash;
    both as a student and teaching &mdash; finally emerging with a doctorate in computer science and a full-time
    professorship. Socially? Not quite as accomplished. He’s had crushes before &mdash; one in particular &mdash; but he’s
    never dared cross the line into something more. For as long as he can remember, he’s been drawn to Noah
    Harper, his best friend since middle school. Seemingly opposites in every way, Cameron’s convinced there’s no
    chance &mdash; but convocation day might just disprove his hypothesis and make him change his questions.
</p>

<p><strong>Noah Harper</strong> has never been an academic. Instead, he's focused his efforts more on athletics. He's
    always been the golden boy &mdash; captain of the WIT hockey team, effortlessly charming, the kind of guy who can fill a
    room just by walking into it. But behind the sinister grin and the wall of trophies lies a gnawing uncertainty: does
    anyone care about him beyond the jersey, about <em>who</em> he is rather than <em>what</em> he is? Sure,
    relationships have come and gone, with men and women alike, but none have stuck. None have meant anything. Then
    Cameron steps onto the graduation stage wearing that cap and gown, and something shifts &mdash; something Noah isn’t ready
    for. Something he can’t ignore any longer, even if exploring it costs him their friendship.
</p>

<p>Two people &mdash; with very different interests &mdash; who have been best friends for years explore the feelings
    they’ve both hidden from each other in this unlikely forbidden romance, exacerbated by Cameron’s graduation and an
    innocent game gone spicy during his after-party. Explore their feelings for each other and what they're
    willing to do (or give up) for each other alongside them as they figure things out for themselves.</p>

