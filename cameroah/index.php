<h3>About the Cameroah Story</h3>
<p><em>Cameroah</em> comes from a portmanteau of the two main characters' names: <strong>Cameron</strong> Thorpe and
    <strong>Noah</strong> Harper. They've been stuck together like glue since they were in middle school. They took most
    of the same classes in high school &mdash; though Cameron focused more in the sciences and mathematics and Noah focused
    more in the humanities and physical education. They both enrolled at the same university, The Waterloo Institute of
    Technology (or, WIT for short), at the same time and pursuing two very different paths. Cameron went t
    hrough three degrees: an Honours Bachelor of Science (HBSc), a Master of Science (MSc), and a Doctor of Science
    (ScD), all in Computer Science, and ended up teaching there during his graduate studies. On the other hand, Noah's
    spent the same time trying to finish his Bachelor of Arts in Communications Technology (BA CommTech). Their
    relationship changes when Noah sees Cameron cross the stage for the third time &mdash; but will it last?</p>

<h3>About The Characters</h3>
<p><strong>Cameron Thorpe</strong>, HBSc, MSc, ScD is a longtime bookworm who enjoys time alone reading or studying,
    usually some sort of science. In his ten years at WIT, he's graduated three times (and participated in the ceremony
    many more than that) so he's intimately familiar with the whole graduation/convocation process. After he did his
    undergraduate work, he started teaching computer science courses, part-time, that is until he graduated from his
    terminal degree: an ScD in Computer Science, graduating at the top of his class and with an offer to teach full-time.
    He's not a people person, but put him at the front of a lecture hall, and he's a whole different person. He's never
    been in any relationships &mdash; mostly because he hasn't tried to pick up any guys, but for some reason, his feelings
    for one guy in particular have been building for quite a while, but does he feel the same way? Cameron doesn't seem
    to think so.</p>
<p><strong>Noah Harper</strong> is WIT's star hockey player. He's the capitan of the team, and with that territory
    comes the long line of guys and girls trying to get with him. He's never been one to enjoy the sciences (Cameron's
    had to tutor him many times) or time alone. Unlike Cameron, he's <em>totally</em> a people person: he'd much prefer
    to be in a large group of people outside or on the rink. He's never been one for solitude or academics. He's had his
    fair share of relationships, but does anyone love him for <em>him</em>, or do they all love him just because of
    <em>what</em> he is? He feels hopeless that he'll ever find true love. Like Cameron, however, his feelings for
    someone special have been brewing for quite a while, and he knows they feel the same way, but would they ever
    consider being something more? Noah's unsure, but is more than willing to experiment, even if it costs him everything.</p>

